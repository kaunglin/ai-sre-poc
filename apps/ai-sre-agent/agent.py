@app.post("/login")
async def login(request: Request):
    if not DASHBOARD_PASSWORD:
        return JSONResponse(
            {"error": "Sign-in is not configured: DASHBOARD_PASSWORD is missing from "
                      "ai-sre-agent-secret. Re-run scripts/deploy-ai-agent.sh."},
            status_code=503)
    try:
        body = await request.json()
    except Exception:
        body = {}
    username = str(body.get("username", ""))
    password = str(body.get("password", ""))
    # Compare both fields, always, in constant time — no early exit that would
    # reveal whether the username alone was right.
    user_ok = hmac.compare_digest(username.encode(), DASHBOARD_USERNAME.encode())
    pass_ok = hmac.compare_digest(password.encode(), DASHBOARD_PASSWORD.encode())
    if not (user_ok and pass_ok):
        await asyncio.sleep(1)  # blunt brute-force throttle
        logger.warning("Dashboard sign-in failed")
        return JSONResponse({"error": "Incorrect username or password"}, status_code=401)
    request.session.clear()
    request.session["user"] = DASHBOARD_USERNAME
    logger.info(f"Dashboard sign-in: {DASHBOARD_USERNAME}")
    return {"ok": True}


