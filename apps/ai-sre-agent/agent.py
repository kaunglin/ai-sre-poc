                    f"*Incident ID:* `{incident.id}`\n"
                    f"*Status:* {incident.status.value}\n"
                    f"*Root cause:* {incident.root_cause}\n"
                    f"*Recommendation:* {incident.recommended_action}\n"
                    f"*Dashboard:* Review and approve at the AI SRE dashboard"
