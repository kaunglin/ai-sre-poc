@asynccontextmanager
async def lifespan(_app: FastAPI):
    store.init()
    resume = await asyncio.to_thread(restore_incidents)
    for inc in resume:
        asyncio.create_task(investigate_incident(inc))
    if not DASHBOARD_PASSWORD:
        logger.warning("DASHBOARD_PASSWORD is not set — dashboard sign-in is disabled")
    if _SESSION_SECRET_GENERATED:
        logger.warning("SESSION_SECRET is not set — using a random one; restarts sign everyone out")
    if not WEBHOOK_TOKEN:
        logger.warning("WEBHOOK_TOKEN is not set — the AlertManager webhook is unauthenticated")
    tasks = [asyncio.create_task(_persist_loop()), asyncio.create_task(_retention_loop())]
    try:
        yield
    finally:
        for t in tasks:
            t.cancel()
        await flush_incidents()


app = FastAPI(title="AI SRE Agent", version="1.0.0", lifespan=lifespan)

