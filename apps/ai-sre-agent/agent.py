class IncidentStore:
    """SQLite persistence for incidents: one row per incident, a JSON blob.

    The in-memory dict stays the working copy (the dedup filter, the dashboard
    and the investigation tasks all read it); SQLite is the durable copy it is
    rebuilt from at startup. Still single-writer, so still replicas: 1 — but a
    restart no longer erases the incident history.
    """

    def __init__(self, path: str):
        self.path = path
        self.enabled = False

    def _connect(self) -> sqlite3.Connection:
        return sqlite3.connect(self.path, timeout=10)

    def init(self) -> None:
        try:
            os.makedirs(os.path.dirname(self.path) or ".", exist_ok=True)
            with self._connect() as db:
                db.execute("PRAGMA journal_mode=WAL")
                db.execute("CREATE TABLE IF NOT EXISTS incidents ("
                           "id TEXT PRIMARY KEY, created_at TEXT NOT NULL, data TEXT NOT NULL)")
                db.execute("CREATE INDEX IF NOT EXISTS incidents_created_at "
                           "ON incidents(created_at)")
            self.enabled = True
            logger.info(f"Incident store: {self.path}")
        except Exception as e:
            logger.error(f"Incident store unavailable ({self.path}): {e} — "
                         "incidents will NOT survive a restart")

    def load_since(self, cutoff: datetime) -> list[dict]:
        with self._connect() as db:
            rows = db.execute("SELECT data FROM incidents WHERE created_at >= ? "
                              "ORDER BY created_at", (cutoff.isoformat(),)).fetchall()
        return [json.loads(r[0]) for r in rows]

    def upsert_many(self, rows: list[tuple[str, str, str]]) -> None:
        with self._connect() as db:
            db.executemany("INSERT INTO incidents (id, created_at, data) VALUES (?, ?, ?) "
                           "ON CONFLICT(id) DO UPDATE SET data = excluded.data", rows)

    def delete_before(self, cutoff: datetime) -> int:
        with self._connect() as db:
            return db.execute("DELETE FROM incidents WHERE created_at < ?",
                              (cutoff.isoformat(),)).rowcount


store = IncidentStore(INCIDENT_DB)


async def flush_incidents() -> None:
    """Write every incident changed since the last flush."""
    dirty = [i for i in incidents.values() if i._dirty]
    if not dirty or not store.enabled:
        return
    # Serialise and clear the flags with no await in between, so a change made
    # by another coroutine either lands in this batch or re-marks the incident.
    rows = [(i.id, i.created_at.isoformat(), json.dumps(i.to_record(), default=str))
            for i in dirty]
    for i in dirty:
        object.__setattr__(i, "_dirty", False)
    try:
        await asyncio.to_thread(store.upsert_many, rows)
    except Exception as e:
        logger.error(f"Failed to persist {len(rows)} incident(s): {e}")
        for i in dirty:
            object.__setattr__(i, "_dirty", True)


def prune_expired() -> int:
    """Drop incidents older than the retention window, in memory and on disk."""
    cutoff = datetime.now(timezone.utc) - timedelta(days=HISTORY_DAYS)
    for iid in [k for k, i in incidents.items() if i.created_at < cutoff]:
        del incidents[iid]
    return store.delete_before(cutoff) if store.enabled else 0


async def _persist_loop() -> None:
    while True:
        await asyncio.sleep(1)
        await flush_incidents()


async def _retention_loop() -> None:
    while True:
        await asyncio.sleep(3600)
        try:
            removed = await asyncio.to_thread(prune_expired)
            if removed:
                logger.info(f"Retention: removed {removed} incident(s) older than {HISTORY_DAYS} days")
        except Exception as e:
            logger.error(f"Retention sweep failed: {e}")


def restore_incidents() -> list["Incident"]:
    """Rebuild the in-memory store from SQLite. Returns incidents to resume.

    An incident caught mid-investigation by the restart is resumed — its
    analysis was going to run anyway. One caught mid-remediation is marked
    FAILED: the patch may or may not have landed, and re-running it blind is
    exactly the kind of action that needs a human to look first.
    """
    if not store.enabled:
        return []
    cutoff = datetime.now(timezone.utc) - timedelta(days=HISTORY_DAYS)
    store.delete_before(cutoff)
    resume = []
    for rec in store.load_since(cutoff):
        try:
            inc = Incident.from_record(rec)
        except Exception as e:
            logger.error(f"Skipping unreadable incident record {rec.get('id')}: {e}")
            continue
        incidents[inc.id] = inc
        if inc.status == IncidentStatus.INVESTIGATING:
            inc.add_event("Agent restarted during investigation — resuming")
            resume.append(inc)
        elif inc.status in (IncidentStatus.APPROVED, IncidentStatus.EXECUTING):
            inc.status = IncidentStatus.FAILED
            inc.remediation_result = ("Agent restarted while the remediation was running — "
                                      "check the deployment's state before retrying")
            inc.add_event("Agent restarted during remediation — outcome unknown")
    logger.info(f"Restored {len(incidents)} incident(s) from the last {HISTORY_DAYS} days")
    return resume

